// テンプレートの {{blankId}} をユーザー入力で置換して指示文を組み立てる。
export function buildInstruction(ex: Exercise, values: Record<string, string>): string {
  return ex.template.replace(/\{\{(\w+)\}\}/g, (_, id: string) => {
    const v = (values[id] ?? "").trim();
    return v.length > 0 ? v : `（${id} 未入力）`;
  });
}

